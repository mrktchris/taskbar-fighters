"""Frame-data QA log: python tools/framedata_log.py [out.md]   (default qa/v9/frame-data.md)

For every fighter and every move that lands: startup / active / recovery / IASA in 60 fps frames (read from the built
anim.json, `framedata.move_frames`), the damage, the hitlag both fighters freeze for, and the knockback, hitstun and
taskbar knockback distance on a target at 0 % and at 40 % (`framedata`), plus a mark when it tumbles.  Then the art
audit (`art/qa_fight.py audit`): weapon flips and cell hops left per fighter, after the V9 fixes.  Numbers only.
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, 'art'))
os.environ.setdefault('MINIS_TESTING', '1')


def main(argv=None):
    argv = argv if argv is not None else sys.argv[1:]
    out = argv[0] if argv else os.path.join(ROOT, 'qa', 'v9', 'frame-data.md')
    from minis_core import choreo, framedata as F
    from minis_core.atlas import Library, available
    lib = Library()
    lines = ['# Frame data (V9)', '',
             'Generated by `python tools/framedata_log.py` from the built sheets. Frames are 1/60 s. kb = knockback units, '
             'stun = hitstun ms, px = taskbar knockback (RES 1 px), at 0 % and at 40 % on a mid-weight target. '
             '"T" = tumbles (a launch arc, then a tech or a knockdown).', '']
    for ch in available():
        a = lib[ch]
        lines += [f'## {a.display} (`{ch}`)', '',
                  '| move | type | startup | active | recovery | IASA | dmg | hitlag ms | kb 0% / 40% | stun 0% / 40% | px 0% / 40% |',
                  '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- | --- |']
        for name, m in a.anim.items():
            if 'hit_frame' not in m or m.get('cat') not in ('strike', 'special', 'super', 'ultimate', 'throw'):
                continue
            kind = m.get('cat') if m.get('cat') in ('special', 'super', 'ultimate') else 'strike'
            st, act, rec, iasa = F.move_frames(a, name)
            dmg = choreo.damage_of(a, name, kind)
            d = dmg * F.PCT_PER_HP
            s, b, ang = F.move_kb(a.power(name, 1), m.get('height'), kind)
            kbs = [F.knockback(p + d, d, F.WEIGHT, s, b) for p in (0.0, 40.0)]
            lag = max(choreo.HITSTOP_FLOOR_MS, F.hitlag_ms(dmg * F.HITLAG_DMG_K))
            fmt = lambda k: f'{k:.0f}' + (' T' if F.tumbles(k) else '')
            lines.append(f"| {name} | {m.get('type') or m.get('cat')} | {st} | {act} | {rec} | {iasa} | {dmg} | {lag:.0f} | "
                         f"{fmt(kbs[0])} / {fmt(kbs[1])} | {F.hitstun_ms(kbs[0]):.0f} / {F.hitstun_ms(kbs[1]):.0f} | "
                         f"{F.taskbar_knock_px(kbs[0]):.0f} / {F.taskbar_knock_px(kbs[1]):.0f} |")
        lines.append('')
    import qa_fight
    rows = qa_fight.audit(None, 1, 14.0, 99.0)
    lines += ['## Art audit after the V9 fixes', '',
              '`art/qa_fight.py audit` (64 px): a flip = a weapon turning 100+ degrees with 14+ px of tip travel between two keys '
              'that are not smears; a cell hop = a row rising 4+ px inside the cell instead of on an `air` curve. Before V9: 300 '
              'flips (250 outside the reactions that snap on purpose and the taunt twirl), 19 cell hops.', '',
              '| fighter | flips | outside snapping reactions / twirl | cell hops |', '| --- | ---: | ---: | ---: |']
    ab = ('thrown', 'spiked', 'launched', 'taunt2')
    for ch in available():
        fl = [r for r in rows if r[1] == ch and r[5] == 'flip']
        lines.append(f"| {ch} | {len(fl)} | {len([r for r in fl if r[2] not in ab])} | "
                     f"{len([r for r in rows if r[1] == ch and r[5] == 'cell-hop'])} |")
    left = [r for r in rows if r[5] == 'flip' and r[2] not in ab]
    lines += ['', 'Left (authored turns, or a long weapon at the edge of the cell):', '']
    lines += [f'- {r[1]} `{r[2]}` frame {r[3]} -> {r[4]}' for r in sorted(left, key=lambda r: (r[1], r[2]))]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
